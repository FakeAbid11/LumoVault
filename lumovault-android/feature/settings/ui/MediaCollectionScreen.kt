@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun MediaCollectionScreen(
    title: String,
    type: MediaCollectionType,
    onBack: () -> Unit,
    onMediaClick: (String) -> Unit,
) {
    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(title) },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.Default.ArrowBack, contentDescription = "Back")
                    }
                },
            )
        }
    ) { padding ->
        Box(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding),
            contentAlignment = Alignment.Center,
        ) {
            Column(
                horizontalAlignment = Alignment.CenterHorizontally,
            ) {
                Icon(
                    imageVector = when (type) {
                        MediaCollectionType.HIDDEN -> Icons.Default.VisibilityOff
                        MediaCollectionType.ARCHIVE -> Icons.Default.Archive
                        MediaCollectionType.TRASH -> Icons.Default.Delete
                        MediaCollectionType.DUPLICATES -> Icons.Default.ContentCopy
                    },
                    contentDescription = null,
                    modifier = Modifier.size(64.dp),
                    tint = MaterialTheme.colorScheme.onSurfaceVariant,
                )
                Text(
                    text = "No items",
                    style = MaterialTheme.typography.bodyLarge,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
        }
    }
}

enum class MediaCollectionType {
    HIDDEN,
    ARCHIVE,
    TRASH,
    DUPLICATES,
}
